#!/usr/bin/env bash
# Writes the WildFly properties of the "cloud" environment for a domain, from the development ones:
#   middleware/wildfly/config/{coldtrace,default-host,admin-host,api,iam}-cloud.properties   (ignored by git)
# The image is then built with ENV=cloud (deploy/docker-compose.cloud.yml). Paths stay the image's (/opt/jboss/www).
#
# Usage: deploy/ubuntu/render-config.sh [DOMAIN]     (default: DOMAIN from gateway-iot/.env)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
DOMAIN="${1:-$(grep -E '^DOMAIN=' "$ROOT/gateway-iot/.env" 2>/dev/null | tail -1 | cut -d= -f2- | tr -d '\r')}"
[[ "$DOMAIN" =~ ^([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$ ]] || { echo "Invalid or missing DOMAIN: '$DOMAIN'" >&2; exit 1; }

CONFIG="$ROOT/middleware/wildfly/config"
for name in coldtrace default-host admin-host api iam; do
  src="$CONFIG/$name-dev.properties"
  dst="$CONFIG/$name-cloud.properties"
  {
    echo "# GENERATED by deploy/ubuntu/render-config.sh for $DOMAIN from $name-dev.properties: do not edit."
    grep -v '^#' "$src" | sed "s/coldtrace\.test/$DOMAIN/g"
  } > "$dst"
done
echo "WildFly configuration written for $DOMAIN (middleware/wildfly/config/*-cloud.properties)."
