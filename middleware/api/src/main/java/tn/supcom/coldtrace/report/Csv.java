package tn.supcom.coldtrace.report;

import org.bson.Document;

import java.io.IOException;
import java.io.Writer;
import java.util.List;

/**
 * CSV exports (RFC 4180, UTF-8 with a byte-order mark so spreadsheet programs show "°C" correctly).
 * A cell that starts with = + - @ is prefixed with ' so a spreadsheet never runs it as a formula.
 */
public final class Csv {

    private Csv() { }

    public static void compliance(Writer out, ReportService.Summary s, List<Document> incidents, String generatedBy)
            throws IOException {
        out.write('﻿');
        row(out, "ColdTrace compliance report");
        row(out, "From", s.from(), "To", s.to(), "Site", s.siteId() == null ? "all" : s.siteId());
        row(out, "Generated at", s.generatedAt(), "Generated by", generatedBy);
        row(out, "Readings", s.readings(), "Compliance %", s.compliancePercent(), "Incidents", s.incidents(),
                "Alarm minutes", s.alarmMinutes(), "Mean time to acknowledge (min)", s.meanAckMinutes(),
                "Unacknowledged", s.unacknowledged());
        out.write("\r\n");
        row(out, "site", "sensor", "name", "profile", "temperature_min_limit", "temperature_max_limit",
                "humidity_min_limit", "humidity_max_limit", "readings", "temperature_min", "temperature_avg",
                "temperature_max", "humidity_avg", "compliance_percent", "incidents", "alarm_minutes",
                "mean_ack_minutes", "unacknowledged", "open");
        for (ReportService.SensorKpi k : s.perSensor()) {
            ReportService.Limits l = k.limits();
            row(out, k.siteId(), k.sensorId(), k.name(), k.profile(), l == null ? null : l.temperatureMin(),
                    l == null ? null : l.temperatureMax(), l == null ? null : l.humidityMin(),
                    l == null ? null : l.humidityMax(), k.readings(), k.temperatureMin(), k.temperatureAvg(),
                    k.temperatureMax(), k.humidityAvg(), k.compliancePercent(), k.incidents(), k.alarmMinutes(),
                    k.meanAckMinutes(), k.unacknowledged(), k.open());
        }
        out.write("\r\n");
        row(out, "incident_id", "site", "sensor", "metric", "status", "opened_at", "closed_at", "value", "peak",
                "threshold_min", "threshold_max", "acknowledged_at", "acknowledged_by", "comment");
        for (Document i : incidents) {
            row(out, i.getObjectId("_id") == null ? null : i.getObjectId("_id").toHexString(), i.getString("siteId"),
                    i.getString("sensorId"), i.getString("metric"), i.getString("status"),
                    ReportService.iso(i.getDate("openedAt")), ReportService.iso(i.getDate("closedAt")), i.get("value"),
                    i.get("peakValue"), i.get("thresholdMin"), i.get("thresholdMax"),
                    ReportService.iso(i.getDate("acknowledgedAt")), i.getString("acknowledgedBy"), i.getString("comment"));
        }
    }

    public static void readingsHeader(Writer out) throws IOException {
        out.write('﻿');
        row(out, "ts", "site", "sensor", "temperature", "humidity", "door_open", "replayed", "msg_id", "received_at");
    }

    public static void reading(Writer out, Document m) throws IOException {
        row(out, ReportService.iso(m.getDate("ts")), m.getString("siteId"), m.getString("sensorId"), m.get("temperature"),
                m.get("humidity"), m.get("doorOpen"), Boolean.TRUE.equals(m.get("replayed")), m.getString("msgId"),
                ReportService.iso(m.getDate("receivedAt")));
    }

    static void row(Writer out, Object... cells) throws IOException {
        for (int i = 0; i < cells.length; i++) {
            if (i > 0) out.write(',');
            out.write(cell(cells[i]));
        }
        out.write("\r\n");
    }

    static String cell(Object value) {
        if (value == null) return "";
        String s = value.toString();
        if (!s.isEmpty() && "=+-@".indexOf(s.charAt(0)) >= 0 && !(value instanceof Number)) s = "'" + s;
        if (s.contains(",") || s.contains("\"") || s.contains("\n") || s.contains("\r")) {
            s = "\"" + s.replace("\"", "\"\"") + "\"";
        }
        return s;
    }
}
